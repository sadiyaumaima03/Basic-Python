a = 3
b = 4

#Performing operations on a, b operands
print(a+b) #Addition 
print(a-b) #Difference
print(a*b) #Multiplication
print(a%b) #Modulus
print(a/b) #Division
print(a**b) #Exponential; multiplies the number by itself as many times mentioned,
            #eg: print(3 ** 4) multiplies 3 by itself four times. 
print(a//b) #Floor Division; divides then rounds to the nearest whole number